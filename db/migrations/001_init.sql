-- Bey Checker schema. The app connects as the database owner; row-level security is enabled with
-- no policies so Supabase's public API roles cannot read or write any table.

create table if not exists settings (
  id integer primary key default 1 check (id = 1),
  data jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists site_assets (
  key text primary key,
  filename text not null,
  mime text not null,
  size integer not null,
  sha256 text not null,
  data bytea not null,
  updated_at timestamptz not null default now()
);

create table if not exists admin_users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  password_hash text not null,
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);

create table if not exists admin_sessions (
  token_hash text primary key,
  admin_id uuid not null references admin_users(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);

create table if not exists rate_limit_hits (
  id bigserial primary key,
  bucket text not null,
  key_hash text not null,
  at timestamptz not null default now()
);
create index if not exists rate_limit_hits_lookup_idx on rate_limit_hits(bucket, key_hash, at);

create table if not exists orders (
  id uuid primary key default gen_random_uuid(),
  reference text not null unique,
  access_token text not null,
  -- Random key generated by the browser for one checkout attempt; makes retries and double
  -- clicks return the same order instead of creating a duplicate.
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  customer_name text not null,
  whatsapp text not null,
  email text,
  delivery_method text not null check (delivery_method in ('whatsapp', 'email')),
  note text not null default '',
  lang text not null default 'en' check (lang in ('en', 'ms')),
  -- Price accepted at the moment the order was created. Never recalculated afterwards.
  currency text not null default 'MYR',
  pricing_unit text not null,
  normal_price numeric(10,2) not null,
  discount numeric(10,2) not null default 0,
  amount_due numeric(10,2) not null check (amount_due > 0),
  promo_label text,
  promo_ends_at timestamptz,
  payment_due_at timestamptz,
  status text not null default 'awaiting_payment' check (status in (
    'awaiting_payment', 'payment_review', 'payment_verified', 'processing', 'completed', 'cancelled')),
  receipt_uploaded_at timestamptz,
  payment_reference text,
  payment_verified_at timestamptz,
  payment_verified_by text,
  payment_rejected_at timestamptz,
  payment_rejection_reason text,
  owner_notes text not null default '',
  authorised_at timestamptz not null,
  terms_accepted_at timestamptz not null,
  closed_at timestamptz
);
create index if not exists orders_created_idx on orders(created_at desc);
create index if not exists orders_status_idx on orders(status);

create table if not exists files (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references orders(id) on delete cascade,
  kind text not null check (kind in ('document', 'receipt')),
  filename text not null,
  mime text not null,
  size integer not null,
  sha256 text not null,
  data bytea not null,
  created_at timestamptz not null default now()
);
create index if not exists files_order_idx on files(order_id);

create table if not exists events (
  id bigserial primary key,
  order_id uuid not null references orders(id) on delete cascade,
  created_at timestamptz not null default now(),
  actor text not null,
  message text not null
);
create index if not exists events_order_idx on events(order_id, created_at);

create table if not exists testimonials (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  display_name text not null,
  feedback text not null,
  rating smallint check (rating is null or rating between 1 and 5),
  consent_confirmed boolean not null default false,
  published boolean not null default false,
  -- A testimonial can only be published with recorded consent.
  check (not published or consent_confirmed)
);

alter table settings enable row level security;
alter table site_assets enable row level security;
alter table admin_users enable row level security;
alter table admin_sessions enable row level security;
alter table rate_limit_hits enable row level security;
alter table orders enable row level security;
alter table files enable row level security;
alter table events enable row level security;
alter table testimonials enable row level security;
